  function getPinnacleReading(value) {
    const n = Number(value);
    if (PINNACLE_READINGS[n]) return PINNACLE_READINGS[n];
    const root = MASTER_ROOTS[n];
    return PINNACLE_READINGS[root] || null;
  }

