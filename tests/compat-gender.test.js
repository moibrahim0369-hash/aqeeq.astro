const G = require('../assets/js/compat-gender.js');
const assert = require('assert');
assert.strictEqual(G.fix('إنت محتاج مساحة وحاسس إنك وحيد', 'female'), 'إنتي محتاجة مساحة وحاسة إنك وحيدة');
assert.strictEqual(G.fix('إنت محتاج مساحة', 'male'), 'إنت محتاج مساحة');
assert.strictEqual(G.fix('إنت محتاج مساحة', ''), 'إنت محتاج مساحة');
assert.strictEqual(G.fix('لما يضحك في وقت صعب، اسأله وقعد معاه', 'female', { third: true }), 'لما تضحك في وقت صعب، اسألها وقعد معاها');
assert.strictEqual(G.fix('إنت محتاج', 'female', { both: true }), 'إنت/ي محتاج/ة');
assert.strictEqual(G.fix('مفيش محتاجين', 'female'), 'مفيش محتاجين');
assert.strictEqual(G.fix('يوم الجمعة', 'female', { third: true }), 'يوم الجمعة');
console.log('compat-gender ok');
