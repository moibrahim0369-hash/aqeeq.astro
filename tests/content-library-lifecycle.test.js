'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Library = require('../assets/js/content-library.js');
const sample = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'assets', 'data', 'content', 'matrix', 'qa-lifecycle-sample.json'), 'utf8'));
assert.equal(Library.validateEntry(sample).valid, true);
assert.equal(Library.isPublic(sample), false);
assert.equal(Library.resolve(sample), null);
const inReview={...sample,workflow:{status:'in-review',publishedAt:null}};
assert.equal(Library.validateEntry(inReview).valid,true);
assert.equal(Library.isPublic(inReview),false);
assert.equal(Library.resolve(inReview),null);
assert.equal(Library.validateEntry({...sample,provenance:{authorship:'only'}}).valid,false);
assert.equal(Library.validateEntry({...sample,workflow:{status:'live'}}).valid,false);
const approved={...sample,workflow:{status:'approved',publishedAt:null},review:{status:'approved',reviewedBy:'qa-reviewer',reviewedAt:'2026-10-28T00:00:00Z'}};
assert.equal(Library.validateEntry(approved).valid,true);
assert.equal(Library.resolve(approved),null);
const published={...approved,workflow:{status:'published',publishedAt:'2026-10-28T00:01:00Z'}};
assert.equal(Library.resolve(published).payload.body,sample.payload.body);
assert.equal(Library.resolve({...published,workflow:{status:'withdrawn',publishedAt:published.workflow.publishedAt}}),null);
(async()=>{let calls=0;const loader=Library.createLoader({version:4,fetch:async url=>{calls++;assert.match(url,/qa-lifecycle-sample\.json\?v=4$/);return{ok:true,json:async()=>sample};}});
assert.equal(await loader.load('matrix/qa-lifecycle-sample.json'),null);
await loader.load('matrix/qa-lifecycle-sample.json');assert.equal(calls,1);
loader.clear();await loader.load('matrix/qa-lifecycle-sample.json');assert.equal(calls,2);
await assert.rejects(()=>loader.load('../private.json'),/path is invalid/);
console.log('Content library lifecycle contract passed: draft → review → approval → publish → withdrawal; validation, versioned cache, invalidation, and path safety verified.');
})().catch(error=>{console.error(error);process.exitCode=1;});
